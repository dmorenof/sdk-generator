<?php
declare(strict_types=1);

namespace Dmorenof\SdkGenerator\Tests;

use Dmorenof\SdkGenerator\Generation\PhpExecutableEmitter;
use Dmorenof\SdkGenerator\Parsing\SpecificationNormalizer;
use InvalidArgumentException;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

/**
 * The OpenAPI dialects read the same way. Every OpenAPI 3.1 fixture of the suite is generated again as 3.2 and as 3.0 by changing
 * nothing but the version: 3.2 must give the very same SDK, and 3.0 either the same or a refusal for the one construct that only 3.1
 * has (listed below, with what the generator says). A new refusal under 3.0, or any difference under 3.2, is a bug in how a dialect is
 * read, found without writing a fixture per dialect and feature.
 */
final class DialectVariantsTest extends TestCase
{
    /** Fixtures that need their referenced files read from disk: they are generated by the command line (`--resolve-local-references`). */
    private const NEED_FILES = ['server-routes'];

    /** What OpenAPI 3.1 has and 3.0 does not, by fixture: the refusal the generator gives for it under 3.0. */
    private const ONLY_IN_31 = [
        'mutual-tls' => 'Unsupported security scheme type',
        'native-schemas' => 'Unsupported type union',
        'request-bodies' => 'Schema must be an object',
        'schema-rules' => 'exclusiveMinimum',
        'accounts-path-items' => 'pathItems',
        'operation-servers-path-items' => 'pathItems',
    ];

    /** @return iterable<string, array{string}> */
    public static function fixtures(): iterable
    {
        $files = glob(__DIR__ . '/fixtures/*-openapi31.json') ?: [];
        sort($files);
        foreach ($files as $file) {
            $name = basename($file, '-openapi31.json');
            if (!in_array($name, self::NEED_FILES, true)) {
                yield $name => [$name];
            }
        }
    }

    /** @return array<string, string> */
    private static function sdk(string $json): array
    {
        $contract = (new SpecificationNormalizer())->fromJson($json);
        return (new PhpExecutableEmitter('Dialect\\Sdk', 'example/dialect-sdk'))->emit($contract);
    }

    private static function withVersion(string $name, string $version): string
    {
        $json = (string) file_get_contents(__DIR__ . "/fixtures/$name-openapi31.json");
        $changed = preg_replace('/"openapi"\s*:\s*"3\.1\.\d+"/', '"openapi": "' . $version . '"', $json, 1, $count);
        self::assertSame(1, $count, "The fixture $name does not declare an OpenAPI 3.1 version.");
        return (string) $changed;
    }

    #[DataProvider('fixtures')]
    public function testOpenApi32GivesTheSameSdkAsOpenApi31(string $name): void
    {
        $base = self::sdk((string) file_get_contents(__DIR__ . "/fixtures/$name-openapi31.json"));

        self::assertSame($base, self::sdk(self::withVersion($name, '3.2.0')));
    }

    #[DataProvider('fixtures')]
    public function testOpenApi30GivesTheSameSdkOrRefusesWhatOnlyOpenApi31Has(string $name): void
    {
        $base = self::sdk((string) file_get_contents(__DIR__ . "/fixtures/$name-openapi31.json"));

        try {
            $sdk = self::sdk(self::withVersion($name, '3.0.3'));
        } catch (InvalidArgumentException $refusal) {
            self::assertArrayHasKey($name, self::ONLY_IN_31, "OpenAPI 3.0 refuses $name, which uses nothing only 3.1 has: {$refusal->getMessage()}");
            self::assertStringContainsString(self::ONLY_IN_31[$name], $refusal->getMessage());
            return;
        }
        self::assertArrayNotHasKey($name, self::ONLY_IN_31, "OpenAPI 3.0 reads $name, which uses something only 3.1 has.");
        self::assertSame($base, $sdk);
    }
}
